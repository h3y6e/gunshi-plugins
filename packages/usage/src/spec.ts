import type { ArgSchema, Args, Command, CommandContext, LazyCommand } from "gunshi/plugin";
import { getCommandSubCommands, isLazyCommand, kebabnize, resolveLazyCommand } from "gunshi/utils";

import type { UsageMeta, UsageOutput } from "./meta.ts";

/** Options of the usage plugin */
export interface UsageOptions {
  /** The display name of the CLI, if not its command name */
  name?: string;
  /** The description of the `usage` command */
  description?: string;
  /**
   * Named sets of flags. A command whose `args` hold every schema of a set, as the same objects,
   * gets `use` in place of those flags.
   */
  flagsets?: Record<string, Args>;
  /**
   * State only what the definitions declare, leaving out what gunshi accepts beyond them: the
   * built-in `--help` and `--version`, extra positionals, and `--flag=true` for a boolean. Global
   * options are stated once with `global=#true`.
   */
  declaredOnly?: boolean;
}

type AnyCommand = Command | LazyCommand;

type Schema = ArgSchema & { env?: string };

type Globals = [string, Schema][];

interface Spec {
  globals: Globals;
  options: UsageOptions;
  used: Map<string, string>;
}

const HEADER = "// @generated by @h3y6e/gunshi-plugin-usage from gunshi metadata";

const BUILTINS = new Set(["help", "version"]);

async function load(command: AnyCommand, name: string): Promise<[Command, UsageMeta]> {
  if (!isLazyCommand(command)) return [command, (command as { usage?: UsageMeta }).usage ?? {}];
  const loaded = await command();
  const once = Object.assign(() => loaded, command);
  return [
    await resolveLazyCommand(once, name, true),
    (loaded as { usage?: UsageMeta }).usage ?? {},
  ];
}

function flagName(key: string, arg: ArgSchema | undefined, toKebab: boolean | undefined) {
  return toKebab || arg?.toKebab ? kebabnize(key) : key;
}

function conflictsOf(arg: ArgSchema): string[] {
  return arg.conflicts === undefined ? [] : [arg.conflicts].flat();
}

function isRequired(arg: ArgSchema): boolean {
  return arg.required ?? (arg.type === "positional" && !arg.multiple && arg.default == null);
}

function q(value: string): string {
  return `"${value
    .toWellFormed()
    .replace(/[\\"\p{C}\p{Zl}\p{Zp}]/gu, (c) =>
      c === "\\" || c === '"' ? `\\${c}` : `\\u{${c.codePointAt(0)?.toString(16)}}`,
    )}"`;
}

function attrs(...items: (string | false | undefined)[]): string {
  return items
    .filter(Boolean)
    .map((item) => ` ${item}`)
    .join("");
}

function defaultAttr(value: string | boolean | number | undefined): string | undefined {
  if (value === undefined) return undefined;
  return typeof value === "boolean" ? `default=#${value}` : `default=${q(String(value))}`;
}

function commonAttrs(arg: ArgSchema): (string | false | undefined)[] {
  return [
    arg.description && `help=${q(arg.description)}`,
    !isRequired(arg) && defaultAttr(arg.default),
    arg.hidden && "hide=#true",
  ];
}

function node(head: string, ...children: (string | false | undefined)[]): string {
  const set = children.filter(Boolean);
  return set.length === 0 ? head : `${head} { ${set.join("; ")} }`;
}

function choicesKdl(arg: ArgSchema): string | undefined {
  if (!arg.choices) return undefined;
  const strict = arg.type === "enum" ? "" : " strict=#false";
  return `choices${strict} ${arg.choices.map((c) => q(c)).join(" ")}`;
}

function childrenOf(arg: Schema, conflictName: (key: string) => string) {
  const conflicts = conflictsOf(arg);
  return [
    choicesKdl(arg),
    conflicts.length > 0 && `conflicts ${conflicts.map((c) => q(conflictName(c))).join(" ")}`,
    arg.complete !== undefined && `complete type=${q(arg.complete)}`,
  ];
}

function flagKdl(
  name: string,
  arg: Schema,
  conflictName: (key: string) => string,
  spec: Spec,
  { action, global }: { action?: string; global?: boolean } = {},
): string {
  const value = arg.type === "boolean" ? "" : ` <${arg.metavar ?? name}>`;
  const spelling = `${arg.short ? `-${arg.short} ` : ""}--${name}${value}`;
  const head = `flag ${q(spelling)}${attrs(
    ...commonAttrs(arg),
    global && "global=#true",
    arg.env !== undefined && !isRequired(arg) && `env=${q(arg.env)}`,
    isRequired(arg) && "required=#true",
    arg.type === "boolean" && !action && !spec.options.declaredOnly && "bool_value=#true",
    arg.type === "boolean" && arg.negatable && `negate=${q(`--no-${name}`)}`,
    arg.multiple && "var=#true",
    action && `action=${q(action)} builtin=#true`,
  )}`;
  return node(head, ...childrenOf(arg, conflictName));
}

function positionalKdl(name: string, arg: Schema, conflictName: (key: string) => string): string {
  const value = isRequired(arg) ? `<${name}>` : `[${name}]`;
  const head = `arg ${q(`${value}${arg.multiple ? "..." : ""}`)}${attrs(...commonAttrs(arg))}`;
  return node(head, ...childrenOf(arg, conflictName));
}

function spellingOf(command: Command, globals: Globals): (key: string) => string {
  const schemas: Record<string, ArgSchema> = { ...Object.fromEntries(globals), ...command.args };
  return (key) => {
    const name = flagName(key, schemas[key], command.toKebab);
    return schemas[key]?.type === "positional" ? name : `--${name}`;
  };
}

function globalKdl(command: Command, spec: Spec, root: boolean): string[] {
  const args: Record<string, Schema> = command.args ?? {};
  const conflictName = spellingOf(command, spec.globals);
  const shorts = new Set(Object.values(args).map((arg) => arg.short));
  return spec.globals.flatMap(([key, arg]) => {
    if (key in args) return [];
    const action = BUILTINS.has(key) ? key : undefined;
    const name = flagName(key, arg, command.toKebab);
    const short = arg.short && !shorts.has(arg.short) ? arg.short : undefined;
    const schema = { ...arg, short };
    if (spec.options.declaredOnly) {
      return root && !action ? [flagKdl(name, schema, conflictName, spec, { global: true })] : [];
    }
    return [flagKdl(name, schema, conflictName, spec, { action })];
  });
}

function setsOf(command: Command, spec: Spec, conflictName: (key: string) => string) {
  const args: Record<string, Schema> = command.args ?? {};
  const sets = new Map<string, string>();
  for (const [set, schemas] of Object.entries(spec.options.flagsets ?? {})) {
    const entries: [string, Schema][] = Object.entries(schemas);
    if (!entries.every(([key, schema]) => args[key] === schema)) continue;
    const body = entries
      .map(([key, s]) => flagKdl(flagName(key, s, command.toKebab), s, conflictName, spec))
      .join("\n");
    if ((spec.used.get(set) ?? body) !== body) continue;
    spec.used.set(set, body);
    for (const [key] of entries) if (!sets.has(key)) sets.set(key, set);
  }
  return sets;
}

function outputKdl(name: string, output: UsageOutput, conflictName: (key: string) => string) {
  const { schema } = output;
  const head = `output ${q(name)}${attrs(
    output.description && `help=${q(output.description)}`,
    output.mediaType && `media_type=${q(output.mediaType)}`,
    output.framing && `framing=${q(output.framing)}`,
    output.select && `select=${q(conflictName(output.select))}`,
    output.default && "default=#true",
    output.hidden && "hide=#true",
  )}`;
  return node(
    head,
    schema !== undefined &&
      (typeof schema === "string" ? `schema ${q(schema)}` : `schema file=${q(schema.file)}`),
  );
}

function bodyKdl(
  command: Command,
  { positionals, subCommands, root }: { positionals: boolean; subCommands: boolean; root: boolean },
  meta: UsageMeta,
  spec: Spec,
): string[] {
  const args: Record<string, Schema> = command.args ?? {};
  const { declaredOnly } = spec.options;
  const body = globalKdl(command, spec, root);
  const conflictName = spellingOf(command, spec.globals);
  const sets = setsOf(command, spec, conflictName);
  const uses = new Set<string>();
  for (const [key, arg] of Object.entries(args)) {
    if (arg.type === "positional" && !positionals) continue;
    const set = sets.get(key);
    if (set !== undefined) {
      if (!uses.has(set)) body.push(`use ${q(set)}`);
      uses.add(set);
      continue;
    }
    const name = flagName(key, arg, command.toKebab);
    body.push(
      arg.type === "positional"
        ? positionalKdl(name, arg, conflictName)
        : flagKdl(name, arg, conflictName, spec),
    );
  }
  const ordered = Object.values(args).filter((arg) => arg.type === "positional");
  const variadic = ordered.some((arg) => arg.multiple);
  const skippable = ordered.findIndex((arg) => !isRequired(arg) && !arg.multiple);
  if (positionals && skippable !== -1 && ordered.slice(skippable).some(isRequired)) {
    body.push("allow_missing_positional #true");
  }
  if (!declaredOnly) {
    if (positionals && !variadic) body.push('arg "[_]..." hide=#true');
    body.push('arg "[__]..." hide=#true double_dash="required"');
  }
  if (subCommands && !declaredOnly) body.push("subcommand_negates_reqs #true");
  for (const [name, output] of Object.entries(meta.outputs ?? {})) {
    body.push(outputKdl(name, output, conflictName));
  }
  for (const [code, text] of Object.entries(meta.exitCodes ?? {})) {
    body.push(`exit_code ${code} ${q(text)}`);
  }
  if (typeof command.examples === "string") body.push(`example ${q(command.examples)}`);
  return body;
}

async function commandKdl(name: string, lazy: AnyCommand, depth: number, spec: Spec) {
  const [command, meta] = await load(lazy, name);
  const indent = "  ".repeat(depth - 1);
  const head = `cmd ${q(name)}${attrs(
    command.description && `help=${q(command.description)}`,
    meta.longDescription && `long_help=${q(meta.longDescription)}`,
    meta.effect && `effect=${q(meta.effect)}`,
    meta.subcommandRequired && "subcommand_required=#true",
    command.internal && "hide=#true",
  )}`;
  const subCommands = getCommandSubCommands(command);
  const lines = bodyKdl(
    command,
    { positionals: !subCommands, subCommands: !!subCommands, root: false },
    meta,
    spec,
  ).map((line) => `${indent}  ${line}`);
  for (const [n, c] of subCommands ?? []) lines.push(await commandKdl(n, c, depth + 1, spec));
  return lines.length === 0
    ? `${indent}${head}`
    : `${indent}${head} {\n${lines.join("\n")}\n${indent}}`;
}

export async function specOf(
  ctx: Readonly<CommandContext>,
  options: UsageOptions,
): Promise<string> {
  // gunshi sets `fallbackToEntry` on the environment, though its type omits it.
  const env: typeof ctx.env & { fallbackToEntry?: boolean } = ctx.env;
  if (!env.name) throw new Error("A usage spec needs the CLI's name; give cli() a name");
  if (!env.entryCommand) throw new Error("A usage spec needs the entry command");
  const [command, meta] = await load(env.entryCommand, env.name);
  const spec: Spec = { globals: [...(env.globalOptions ?? [])], options, used: new Map() };
  const lines = [
    `name ${q(options.name ?? env.name)}`,
    `bin ${q(env.name)}`,
    ...(env.version ? [`version ${q(env.version)}`] : []),
    ...(env.description ? [`about ${q(env.description)}`] : []),
    ...(meta.longDescription ? [`long_about ${q(meta.longDescription)}`] : []),
    ...(options.declaredOnly ? [] : ["disable_help #true", "disable_version_flag #true"]),
    ...(env.strict ? ['unknown_flags "error"'] : []),
  ];
  const subCommands = [...(env.subCommands ?? [])].filter(([, sub]) => sub !== env.entryCommand);
  const body = bodyKdl(
    command,
    {
      positionals: env.fallbackToEntry || subCommands.length === 0,
      subCommands: subCommands.length > 0,
      root: true,
    },
    meta,
    spec,
  );
  for (const [name, sub] of subCommands) body.push(await commandKdl(name, sub, 1, spec));
  const flagsets = [...spec.used].map(
    ([name, flags]) => `flagset ${q(name)} {\n${flags.replace(/^/gm, "  ")}\n}`,
  );
  return [HEADER, ...lines, ...flagsets, ...body].join("\n");
}
