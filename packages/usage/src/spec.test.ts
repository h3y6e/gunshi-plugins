import usage from "./index.ts";

type Options = NonNullable<Parameters<typeof cli>[2]>;

async function generate(entry: Parameters<typeof cli>[1], options: Options): Promise<string> {
  const log = vi.spyOn(console, "log").mockImplementation(() => {});
  await cli(["usage"], entry, { ...options, plugins: [...(options.plugins ?? []), usage()] });
  const spec = log.mock.calls.map((call) => call.join(" ")).join("\n");
  log.mockRestore();
  return spec;
}

const sync = define({
  name: "sync",
  description: "Sync a project",
  toKebab: true,
  examples: "app sync web --dry-run",
  args: {
    project: { type: "positional", description: "Project name" },
    dryRun: { type: "boolean", description: "Show the plan only" },
    jobs: { type: "number", description: "Parallel jobs" },
    mode: { type: "enum", choices: ["fast", "safe"], description: "Sync mode" },
    tag: { type: "string", multiple: true, description: "Tags to sync" },
    color: { type: "boolean", negatable: true, default: true, description: "Colorize output" },
    out: {
      type: "string",
      metavar: "FILE",
      conflicts: ["stdout", "dryRun"],
      description: "Output file",
    },
    stdout: { type: "boolean", description: "Write to stdout" },
    trace: { type: "boolean", hidden: true },
  },
  run: (c) => console.log(`jobs=${c.values.jobs}`),
});

const status = define({
  name: "status",
  description: "Show status",
  args: {
    json: { type: "boolean", description: "Print JSON" },
    host: { type: "string", description: "Host to query" },
  },
  run: (c) => console.log(`host=${c.values.host}`),
});

const entry = define({ name: "app", run: () => {} });

const options = {
  name: "app",
  version: "1.2.3",
  description: "Sample app",
  subCommands: {
    status,
    sync,
    remote: lazy(async () => define({ name: "remote", run: () => {} }), {
      name: "remote",
      description: "Manage remotes",
    }),
    debug: define({ name: "debug", internal: true, run: () => {} }),
  },
  strict: true,
  renderHeader: null,
};

async function runApp(argv: string[]): Promise<string> {
  const log = vi.spyOn(console, "log").mockImplementation(() => {});
  await cli(argv, entry, options);
  return log.mock.calls.map((call) => call.join(" ")).join("\n");
}

function lint(kdl: string) {
  const dir = mkdtempSync(join(tmpdir(), "gunshi-plugin-usage-lint-"));
  try {
    writeFileSync(join(dir, "lint.usage.kdl"), kdl);
    return spawnSync("usage", ["lint", join(dir, "lint.usage.kdl")], { encoding: "utf8" });
  } finally {
    rmSync(dir, { recursive: true });
  }
}

async function writeSpec(
  entry: Parameters<typeof generate>[0],
  options: Options,
  path: string,
): Promise<void> {
  writeFileSync(path, `${await generate(entry, options)}\n`);
}

