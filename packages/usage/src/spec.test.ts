describe("top level and nesting", () => {
  test("when the entry command declares examples and a command nests another, the spec carries each at its level", async () => {
    // Arrange
    const app = define({
      name: "app",
      examples: "app web",
      run: () => {},
    });
    const inner = define({ name: "inner", run: () => {} });
    const outer = define({ name: "outer", subCommands: { inner }, run: () => {} });

    // Act
    const kdl = await generate(app, {
      name: "app",
      subCommands: { outer },
    });

    // Assert
    expect(kdl).toContain('example "app web"');
    expect(kdl).toMatch(/^subcommand_negates_reqs #true$/m);
    expect(kdl).toContain(
      [
        'cmd "outer" {',
        '  flag "-h --help" help="Display this help message" action="help" builtin=#true',
        '  flag "-v --version" help="Display this version" action="version" builtin=#true',
        '  arg "[__]..." hide=#true double_dash="required"',
        "  subcommand_negates_reqs #true",
        '  cmd "inner" {',
        '    flag "-h --help" help="Display this help message" action="help" builtin=#true',
        '    flag "-v --version" help="Display this version" action="version" builtin=#true',
        '    arg "[_]..." hide=#true',
        '    arg "[__]..." hide=#true double_dash="required"',
        "  }",
        "}",
      ].join("\n"),
    );
    const result = lint(kdl);
    expect(result.status, `${result.stdout}${result.stderr}`).toBe(0);
  });
});

describe("KDL strings", () => {
  test("when a description has quotes, backslashes, control characters, and non-ASCII text, usage lint accepts the spec and reads the text back", async () => {
    // Arrange
    const text = 'say "hi" \\ tab\t bell\u0007 literal \\u0041 \u0085 \u2028 \u200e \ufeff 日本語';

    // Act
    await writeSpec(
      define({ name: "app", run: () => {} }),
      {
        name: "app",
        description: text,
      },
      join(dir, "app.usage.kdl"),
    );

    // Assert
    const lint = spawnSync("usage", ["lint", join(dir, "app.usage.kdl")], { encoding: "utf8" });
    expect(lint.status, lint.stdout + lint.stderr).toBe(0);
    const json = spawnSync("usage", ["generate", "json", "-f", join(dir, "app.usage.kdl")], {
      encoding: "utf8",
    });
    expect(JSON.parse(json.stdout).about).toBe(text);
  });
});

describe("spec fidelity", () => {
  beforeAll(async () => {
    await writeSpec(entry, options, join(dir, "app.usage.kdl"));
  });

  test.each([
    { argv: ["sync", "web", "--dry-run"], accepted: true },
    { argv: ["sync", "web", "--no-color", "--tag", "a", "--tag", "b"], accepted: true },
    { argv: ["sync", "web", "--mode", "turbo"], accepted: false },
    { argv: ["sync", "web", "--out", "x", "--stdout"], accepted: false },
    { argv: ["sync", "web", "--out", "x", "--dry-run"], accepted: false },
    { argv: ["sync", "web", "--bogus"], accepted: false },
    { argv: ["sync"], accepted: false },
    { argv: ["-v"], accepted: true },
    { argv: ["-V"], accepted: false },
    { argv: ["help"], accepted: false },
    { argv: ["sync", "-h"], accepted: true },
  ])(
    "when gunshi parses $argv, usage explain reaches the same verdict",
    async ({ argv, accepted }) => {
      // Arrange
      const spec = join(dir, "app.usage.kdl");

      // Act
      const explain = spawnSync(
        "usage",
        ["explain", "-f", spec, "--format", "json", "--", "app", ...argv],
        { encoding: "utf8" },
      );
      const report = JSON.parse(explain.stdout);
      const gunshi = await runApp(argv).then(
        () => true,
        () => false,
      );

      // Assert
      expect(report.errors.length === 0 && report.refused === null).toBe(accepted);
      expect(gunshi).toBe(accepted);
    },
  );
});

describe("gunshi semantics", () => {
  async function verdicts(entry: Parameters<typeof cli>[1], options: Options, argv: string[]) {
    const spec = join(dir, "semantics.usage.kdl");
    const kdl = await generate(entry, options);
    writeFileSync(spec, kdl);
    const explain = spawnSync(
      "usage",
      ["explain", "-f", spec, "--format", "json", "--", String(options.name), ...argv],
      { encoding: "utf8" },
    );
    const report = JSON.parse(explain.stdout);
    vi.spyOn(console, "log").mockImplementation(() => {});
    const gunshi = await cli(argv, entry, {
      ...options,
      renderHeader: null,
      renderValidationErrors: null,
      plugins: [...(options.plugins ?? []), usage()],
    }).then(
      () => true,
      () => false,
    );
    return {
      usage: report.errors.length === 0 && report.refused === null,
      gunshi,
      lint: lint(kdl).status,
    };
  }

  const run = () => {};
  const sub = define({ name: "sub", run });
  const kebab = plugin({
    id: "x:kebab",
    setup: (ctx) => ctx.addGlobalOption("dryRun", { type: "boolean" }),
  });

  test.each([
    {
      case: "fallbackToEntry is true beside sub-commands",
      entry: define({ name: "app", args: { name: { type: "positional" } }, run }),
      options: { name: "app", subCommands: { sub }, fallbackToEntry: true },
      argv: ["world"],
      accepted: true,
    },
    {
      case: "a required arg has a default",
      entry: define({
        name: "app",
        args: { s: { type: "string", required: true, default: "a" } },
        run,
      }),
      options: { name: "app" },
      argv: [],
      accepted: false,
    },
    {
      case: "an optional positional precedes a required one",
      entry: define({
        name: "app",
        args: { src: { type: "positional", required: false }, dest: { type: "positional" } },
        run,
      }),
      options: { name: "app" },
      argv: ["only"],
      accepted: true,
    },
    {
      case: "a flag conflicts with a given positional",
      entry: define({
        name: "app",
        args: {
          from: { type: "string", conflicts: "target" },
          target: { type: "positional", required: false },
        },
        run,
      }),
      options: { name: "app" },
      argv: ["--from", "a", "x"],
      accepted: false,
    },
    {
      case: "two positionals share a metavar",
      entry: define({
        name: "app",
        args: {
          src: { type: "positional", metavar: "string" },
          dest: { type: "positional", metavar: "string" },
        },
        run,
      }),
      options: { name: "app" },
      argv: ["a"],
      accepted: false,
    },
    {
      case: "a command flag takes the short letter of a global",
      entry: define({ name: "app", args: { verbose: { type: "boolean", short: "v" } }, run }),
      options: { name: "app", version: "1.0.0" },
      argv: ["-v"],
      accepted: true,
    },
    {
      case: "a toKebab command has a plugin's global option",
      entry: define({ name: "app", run }),
      options: {
        name: "app",
        subCommands: { sub: define({ name: "sub", toKebab: true, run }) },
        plugins: [kebab],
      },
      argv: ["sub", "--dry-run"],
      accepted: true,
    },
    {
      case: "a global option conflicts with a toKebab command flag",
      entry: define({ name: "app", toKebab: true, args: { forceAll: { type: "boolean" } }, run }),
      options: {
        name: "app",
        plugins: [
          plugin({
            id: "x:global-conflict",
            setup: (ctx) =>
              ctx.addGlobalOption("quiet", { type: "boolean", conflicts: "forceAll" }),
          }),
        ],
      },
      argv: ["--quiet", "--force-all"],
      accepted: false,
    },
    {
      case: "a command flag conflicts with a toKebab global option",
      entry: define({
        name: "app",
        args: { force: { type: "boolean", conflicts: "dryRun" } },
        run,
      }),
      options: {
        name: "app",
        plugins: [
          plugin({
            id: "x:kebab-global",
            setup: (ctx) => ctx.addGlobalOption("dryRun", { type: "boolean", toKebab: true }),
          }),
        ],
      },
      argv: ["--force", "--dry-run"],
      accepted: false,
    },
  ])(
    "when $case, gunshi and usage explain agree on $argv and usage lint accepts the spec",
    async ({ entry, options, argv, accepted }) => {
      // Arrange
      const expected = { usage: accepted, gunshi: accepted, lint: 0 };

      // Act
      const actual = await verdicts(entry, options as Options, argv);

      // Assert
      expect(actual).toEqual(expected);
    },
  );

  test("when a sub-command declares its own version arg, the spec gives that command the arg instead of the builtin", async () => {
    // Arrange
    const install = define({ name: "install", args: { version: { type: "string" } }, run });

    // Act
    const kdl = await generate(define({ name: "app", run }), {
      name: "app",
      version: "1.0.0",
      subCommands: { install },
    });

    // Assert
    const block = kdl.slice(kdl.indexOf('cmd "install"'));
    expect(block).toContain('flag "--version <version>"');
    expect(block.slice(0, block.indexOf("}"))).not.toContain('action="version"');
  });

  test("when a command gives examples as a function, the spec leaves them out", async () => {
    // Arrange
    const app = define({ name: "app", examples: async () => "app --dynamic", run });

    // Act
    const kdl = await generate(app, { name: "app" });

    // Assert
    expect(kdl).not.toContain("example");
  });

  test("when usageSilent is set, the usage command still prints the spec", async () => {
    // Arrange
    const options = { name: "app", usageSilent: true };

    // Act
    const kdl = await generate(define({ name: "app", run }), options);

    // Assert
    expect(kdl).toMatch(/^name "app"$/m);
  });

  test("when a description has a lone surrogate, usage lint accepts the spec", async () => {
    // Arrange
    const app = define({ name: "app", description: "broken \uD83D tail", run });

    // Act
    const kdl = await generate(app, { name: "app" });

    // Assert
    expect(lint(kdl).status).toBe(0);
  });
});
